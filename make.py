# Запустите этот скрипт локально у себя, чтобы собрать чистый main.py без фильтров
lines = [
    "import os, sys, json, time, requests, torch, re, urllib.parse\n",
    "TTS_ENGINE = None\n",
    "SERVER_URL = 'https://skulla.ru'\n\n",
    "def init_vton_models():\n",
    "    global TTS_ENGINE\n",
    "    os.environ['COQUI_TOS_AGREED'] = '1'\n",
    "    try:\n",
    "        from TTS.api import TTS\n",
    "        TTS_ENGINE = TTS(model_name='tts_models/multilingual/multi-dataset/xtts_v2').to('cuda')\n",
    "    except Exception as e: print(e)\n\n",
    "def process_voice_chat(task_data):\n",
    "    global TTS_ENGINE\n",
    "    actual = task_data.get('task_data', {})\n",
    "    t_id = actual.get('task_id')\n",
    "    s_id = actual.get('session_id')\n",
    "    u_login = actual.get('user_login')\n",
    "    web_msg = actual.get('text_message', '')\n",
    "    s_dir = f'./uploads/{s_id}'\n",
    "    os.makedirs(s_dir, exist_ok=True)\n",
    "    in_wav = os.path.join(s_dir, 'user_voice.wav')\n",
    "    out_wav = 'bot_response.wav'\n",
    "    dl_url = f'{SERVER_URL}/api/studio/fishhook/download_source/{s_id}?filename=user_voice.wav'\n",
    "    try:\n",
    "        res = requests.get(dl_url, timeout=20)\n",
    "        if res.status_code == 200:\n",
    "            with open(in_wav, 'wb') as f: f.write(res.content)\n",
    "    except Exception as e: print(e)\n",
    "    u_txt = web_msg.strip()\n",
    "    if not u_txt and os.path.exists(in_wav):\n",
    "        try:\n",
    "            import whisper\n",
    "            model = whisper.load_model('base')\n",
    "            result = model.transcribe(in_wav, language='russian')\n",
    "            u_txt = result.get('text', '')\n",
    "        except Exception as e: print(e)\n",
    "    if not u_txt.strip(): u_txt = 'Привет'\n",
    "    try:\n",
    "        if TTS_ENGINE is not None and os.path.exists(in_wav):\n",
    "            TTS_ENGINE.tts_to_file(text=u_txt, language='ru', speaker_wav=in_wav, file_path=out_wav)\n",
    "    except Exception as e:\n",
    "        print(e)\n",
    "        try:\n",
    "            from gtts import gTTS\n",
    "            gTTS(text=u_txt, lang='ru').save(out_wav)\n",
    "        except: pass\n",
    "    try:\n",
    "        enc_u = urllib.parse.quote(u_txt)\n",
    "        up_url = f'{SERVER_URL}/api/studio/fishhook/submit_result?task_id={t_id}&user_login={u_login}&user_text={enc_u}&bot_text={enc_u}'\n",
    "        with open(out_wav, 'rb') as f:\n",
    "            requests.post(up_url, data={'task_id':t_id, 'user_login':u_login}, files={'image':(out_wav, f, 'audio/wav')}, timeout=30)\n",
    "        if os.path.exists(in_wav): os.remove(in_wav)\n",
    "        if os.path.exists(out_wav): os.remove(out_wav)\n",
    "    except Exception as e: print(e)\n\n",
    "def main_loop(user_login):\n",
    "    init_vton_models()\n",
    "    endpoint = f'{SERVER_URL}/api/studio/fishhook/get_task/{user_login.lower().strip()}'\n",
    "    while True:\n",
    "        try:\n",
    "            res = requests.get(endpoint, timeout=10)\n",
    "            if res.status_code == 200:\n",
    "                data = res.json()\n",
    "                if data.get('status') == 'success': process_voice_chat(data)\n",
    "        except Exception as e: print(e)\n",
    "        time.sleep(2)\n\n",
    "if __name__ == '__main__':\n",
    "    import argparse\n",
    "    p = argparse.ArgumentParser()\n",
    "    p.add_argument('--login', type=str, required=True)\n",
    "    main_loop(p.parse_args().login)\n"
]

with open("main.py", "w", encoding="utf-8") as f:
    f.writelines(lines)
print("Файл main.py успешно собран и записан на диск!")
