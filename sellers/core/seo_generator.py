import os

class SkullaSEOGenerator:
    @staticmethod
    def generate_description(product_name, brand_name, feature_1, feature_2, promo_tag, platform="wildberries"):
        """
        Высокоточный алгоритмический SEO-генератор описаний для маркетплейсов.
        Работает без ЛЛМ, бесплатно и мгновенно внедряет LSI-ключевики.
        """
        # Чистим входящие строки от мусора и смайликов для чистоты текста
        p_name = str(product_name).strip()
        b_name = str(brand_name).strip() if brand_name else "Оригинал"
        f1 = str(feature_1).replace("🔥", "").replace("⚡", "").replace("💎", "").strip()
        f2 = str(feature_2).replace("🔥", "").replace("⚡", "").replace("💎", "").strip()
        promo = str(promo_tag).replace("🎁", "").strip()

        # Базовые универсальные LSI-ключи для вылета карточки в ТОП выдачи
        lsi_keywords = "купить на маркетплейсе, быстрая доставка, высокое качество, премиум материалы, надежный бренд, идеальный подарок"
        
        # Специфические SEO-теги под конкретные площадки
        if str(platform).lower() == "wildberries":
            target_marketplace = "Wildberries (Вайлдберриз)"
            seo_footer_tags = f"#wb #вайлдберриз #акция #тренды2026 #стиль #{p_name.lower().replace(' ', '')}"
        else:
            target_marketplace = "Ozon (Озон) и Яндекс.Маркет"
            seo_footer_tags = f"#ozon #озон #яндексмаркет #топпродаж #оригинал #{p_name.lower().replace(' ', '')}"

        # 🧱 КОНСТРУКТОР ПРОДАЮЩЕГО ТЕКСТА (Структурирован по правилам коммерческого копирайтинга)
        paragraphs = [
            f"Ищете качественный и надежный товар? Представляем вам {p_name} от ведущего бренда {b_name}! Это идеальное решение для тех, кто ценит премиум материалы, долговечность и современный стиль. Наш продукт разработан с учетом строгих стандартов качества, чтобы превзойти все ваши ожидания.",
            
            f"Главные преимущества и свойства товара, которые выделяют его среди конкурентов:\n"
            f"✅ {f1 if f1 else 'Высокое качество сборки и эргономичный дизайн'}\n"
            f"✅ {f2 if f2 else 'Максимальная надежность при ежедневном использовании'}\n"
            f"Каждая деталь продумана до мелочей, что делает {p_name} отличным выбором как для личного использования, так и в качестве стильного подарка для близких.",
            
            f"🔥 Обратите внимание! Прямо сейчас действует специальное предложение: {promo if promo else 'Выгодная цена по акции'}. Успейте купить на маркетплейсе {target_marketplace} с гарантией оригинальности бренда и быстрой безопасной доставкой до вашего пункта выдачи. Добавьте товар в избранное, чтобы не пропустить закрытые распродажи!",
            
            f"📌 Ключевые слова для поиска (SEO): {lsi_keywords}, {p_name.lower()}, {b_name.lower()}.\n"
            f"{seo_footer_tags}"
        ]

        # Собираем монолитное SEO-описание
        full_seo_text = "\n\n".join(paragraphs)
        
        # Генерируем пак из 15 скрытых поисковых тегов для заполнения полей карточки
        tags_list = [
            p_name.lower(), 
            f"{p_name.lower()} {b_name.lower()}", 
            "купить со скидкой", 
            "лучший товар 2026", 
            "премиум качество", 
            "в наличии",
            "оригинальная продукция",
            "подарок",
            "топ продаж"
        ]
        
        return {
            "status": "success",
            "platform": platform,
            "description": full_seo_text,
            "seo_tags": tags_list
        }
