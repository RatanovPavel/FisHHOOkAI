// 3. Твоя обновленная функция открытия с дизайном
function openLegal(type) {
    const docs = getLegalDocs(); // 🎯 Собираем тексты в момент клика
    const doc = docs[type];
    
    if (!doc) return;

    const container = document.getElementById('auth-content');
    if (!container) return;

    container.innerHTML = `
        <div class="relative w-full h-full">
            <button onclick="closeAuthModal()" 
                    class="absolute -top-6 -right-4 z-50 p-2 text-slate-500 hover:text-cyan-400 text-3xl transition-all duration-300 hover:rotate-90">
                ✕
            </button>

            <div class="max-h-[70vh] overflow-y-auto pr-4 max-w-[92%] custom-scrollbar" id="legal-scroll-area">
                <div class="mb-10 border-b border-white/5 pb-6">
                    <h2 class="text-xl font-black text-white m-0 tracking-tight leading-tight uppercase">
                        ${doc.title}
                    </h2>
                </div>
                
                <div class="space-y-8 text-slate-400 text-[12px] leading-relaxed">
                    ${doc.content}
                </div>
                
                ${getLegalFooter()}
            </div>
        </div>
    `;

    const modal = document.getElementById('auth-modal');
    if (modal) {
        modal.style.display = 'flex';
        modal.classList.remove('hidden');
        console.log(`🍏 [SKULLA LEGAL SUCCESS]: Документ [${type}] успешно выведен на экран!`);
    }
    document.getElementById('legal-scroll-area').scrollTop = 0;
}
